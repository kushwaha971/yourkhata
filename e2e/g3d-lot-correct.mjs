// Correcting a mistyped karigar lot: a wrong weight given and a wrong weight back
// are fixed through the dialog and the wastage follows (--skew expects 1.5: must
// fail); heavier-than-given is refused; a mistaken lot is removed after asking; a
// lot with tags offers no Remove; the karigar's limit is edited; L 390, 320.
import { randomUUID } from 'node:crypto';
import { mkdirSync } from 'node:fs';
import { chromium } from 'playwright';
const base = process.env.E2E_BASE ?? 'http://localhost:3005';
const api = `${base}/api/v1`;
const skew = process.argv.includes('--skew');
const dir = '/tmp/e2e-shots/g3d';
mkdirSync(dir, { recursive: true });
const run = Date.now().toString(36).toUpperCase().slice(-5);
const results = [];
const check = (n, ok, d = '') => { results.push(ok); console.log(`${ok ? '  ok ' : 'FAIL '} ${n}${d ? ` — ${d}` : ''}`); };
let errs = 0;
const watch = (p) => p.on('console', (m) => { if (m.type() === 'error' && !/favicon|Failed to load/.test(m.text())) { errs += 1; console.log(m.text().slice(0, 160)); } });
const browser = await chromium.launch({ executablePath: process.env.PW_CHROME });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 } });
const page = await ctx.newPage();
watch(page);
await page.goto(`${base}/login/email`);
await page.fill('input[type=email]', 'qa-jeweller@adcert.test');
await page.fill('input[type=password]', 'AdCert-Test-2026!');
await page.keyboard.press('Enter');
await page.waitForURL((u) => !u.pathname.startsWith('/login'), { timeout: 30000 });
const hdr = async () => ({ 'X-CSRF-Token': (await ctx.cookies()).find((c) => c.name === 'ub_csrf')?.value ?? '', 'Idempotency-Key': randomUUID() });
const get = async (p) => (await (await ctx.request.get(`${api}${p}`)).json()).data;
const post = async (p, data) => (await (await ctx.request.post(`${api}${p}`, { headers: await hdr(), data })).json()).data;
const name = `Sunil ${run}`;
const k = await post('/sales/karigars', { name, wastage_limit_pct: '1.5' });
const me = async () => (await get('/sales/karigars')).rows.find((r) => r.id === k.id);
const open1 = await post(`/sales/karigars/${k.id}/issue`, { weight_g: '374', purity: 'gold_22k', client_key: randomUUID() });
await page.goto(`${base}/sales/custom-orders`);
const lotRow = page.getByTestId('karigar-lot').filter({ hasText: name });
await lotRow.getByTestId('karigar-lot-correct').click();
let d = page.getByRole('dialog');
await d.getByLabel('Weight given').fill('37.400');
await page.getByTestId('karigar-save').click();
await d.waitFor({ state: 'detached', timeout: 10000 }).catch(() => undefined);
await page.waitForTimeout(900);
check('a wrong weight given is corrected', (await me()).with_g === '37.400', (await me()).with_g);
await post(`/sales/karigar-lots/${open1.id}/receive`, { received_g: '30' });
await page.reload();
const back = page.getByTestId('karigar-to-tag').filter({ hasText: name });
await back.getByTestId('karigar-lot-correct').click();
d = page.getByRole('dialog');
await d.getByLabel('Weight received').fill('40');
await page.getByTestId('karigar-save').click();
await page.getByText('More than the 37.400 g given').first().waitFor({ timeout: 8000 }).catch(() => undefined);
check('heavier than given is said in the dialog', (await page.getByText('More than the 37.400 g given').count()) >= 1);
await page.screenshot({ path: `${dir}/correct-1280.png` });
await d.getByLabel('Weight received').fill('36.880');
await page.getByTestId('karigar-save').click();
await d.waitFor({ state: 'detached', timeout: 10000 }).catch(() => undefined);
await page.waitForTimeout(900);
const want = skew ? '1.5' : '1.4';
check(`the wastage follows: ${want}%`, (await me()).wastage_pct === want, (await me()).wastage_pct);
check('…on screen, within the limit', (await page.getByTestId('karigar-row').filter({ hasText: name }).getByText('1.4% · within 1.5%').count()) === 1);
await post(`/sales/karigars/${k.id}/issue`, { weight_g: '99', purity: 'gold_22k', client_key: randomUUID() });
await page.reload();
await page.getByTestId('karigar-lot').filter({ hasText: name }).getByTestId('karigar-lot-correct').click();
await page.getByTestId('karigar-lot-remove').click();
await page.getByRole('alertdialog').or(page.getByRole('dialog').filter({ hasText: 'Remove this gold?' })).getByRole('button', { name: 'Remove', exact: true }).last().click();
await page.waitForTimeout(1200);
check('a mistaken lot is removed after asking', (await me()).with_g === '0.000', (await me()).with_g);
const row = page.getByTestId('karigar-row').filter({ hasText: name });
await row.getByTestId('karigar-edit').click();
d = page.getByRole('dialog');
await d.getByLabel('Wastage allowed').fill('1');
await page.getByTestId('karigar-save').click();
await d.waitFor({ state: 'detached', timeout: 10000 }).catch(() => undefined);
await page.waitForTimeout(900);
check('the limit is edited, and the row now says over', (await me()).over_limit === true && (await row.getByText(/over 1%/).count()) === 1);
const nos = (await get('/units')).find((u) => u.code === 'NOS');
const item = await post('/items', { name: `G3d chain ${run}`, unit_id: nos.id, selling_price: '0', tracking: 'serial' });
await post(`/sales/karigar-lots/${open1.id}/tags`, { item_id: item.id, tag: { tag_no: `CR-${run}`, purity: 'gold_22k', gross_g: '5', net_g: '5', making_type: 'pct', making_value: '0' } });
await page.reload();
await page.getByTestId('karigar-to-tag').filter({ hasText: name }).getByTestId('karigar-lot-correct').click();
await page.getByRole('dialog').getByLabel('Weight given').waitFor({ timeout: 10000 });
check('a lot with tags offers no Remove', (await page.getByTestId('karigar-lot-remove').count()) === 0);
const host = new URL(base).hostname;
const state = await ctx.storageState();
for (const [width, theme] of [[390, 'light'], [320, 'dark']]) {
  const c = await browser.newContext({ storageState: state, viewport: { width, height: 800 } });
  await c.addCookies([{ name: 'ub_theme_choice', value: theme, domain: host, path: '/' }]);
  const p = await c.newPage();
  watch(p);
  await p.goto(`${base}/sales/custom-orders`);
  const r = p.getByTestId('karigar-to-tag').filter({ hasText: name });
  await r.waitFor({ timeout: 15000 });
  await r.scrollIntoViewIfNeeded();
  await p.screenshot({ path: `${dir}/row-${width}-${theme}.png` });
  const over = await p.evaluate(() => document.documentElement.scrollWidth - innerWidth);
  check(`L ${width} ${theme}: page fits`, over <= 0, `${over}px`);
  await r.getByTestId('karigar-lot-correct').click();
  await p.getByRole('dialog').getByLabel('Weight given').waitFor({ timeout: 10000 });
  await p.screenshot({ path: `${dir}/dialog-${width}-${theme}.png` });
  await c.close();
}
await browser.close();
const failed = results.filter((x) => !x).length;
console.log(`\n${results.length - failed}/${results.length} passed, ${errs} console errors${skew ? ' (SKEWED)' : ''}`);
process.exitCode = skew ? (failed ? 0 : 1) : failed || errs ? 1 : 0;
