const HINDI: Readonly<Record<string, HindiCopy>> = { ...MODULE_PAGES, ...SHOP_KIND_HI };

/** Every slug that has a Hindi page, in the English page order. */
export const HINDI_SLUGS: readonly string[] = Object.keys(HINDI);

/** The Hindi page: the English entry's slug and pictures, the Hindi words. */
export const hindiSolutionBySlug = (slug: string): Solution | undefined => {
  const english = solutionBySlug(slug);
  const copy = HINDI[slug];
  if (!english || !copy) return undefined;
  return { ...english, video: undefined, example: undefined, cases: undefined, ...copy };
};
