// G3 — a custom order becomes its bill: Make bill opens a bill for the customer,
// a scanned tag takes the order's FIXED rate although today's rate has moved, the
// advance comes off To pay, and issuing delivers the order.
//   node e2e/g3o-order-bill.mjs [--skew]
import { mkdirSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { chromium } from 'playwright';
const base = process.env.E2E_BASE ?? 'http://localhost:3005';
const api = `${base}/api/v1`;
const skew = process.argv.includes('--skew');
const dir = '/tmp/e2e-shots/g3o';
mkdirSync(dir, { recursive: true });
const run = Date.now().toString(36).toUpperCase().slice(-5);
const results = [];
const check = (n, ok, d = '') => { results.push(ok); console.log(`${ok ? '  ok ' : 'FAIL '} ${n}${d ? ` — ${d}` : ''}`); };
let errs = 0;
const browser = await chromium.launch({ executablePath: process.env.PW_CHROME });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 } });
const page = await ctx.newPage();
page.on('console', (m) => { if (m.type() === 'error' && !/favicon|Failed to load/.test(m.text())) { errs += 1; console.log(m.text().slice(0, 160)); } });
await page.goto(`${base}/login/email`);
await page.fill('input[type=email]', 'qa-jeweller@adcert.test');
await page.fill('input[type=password]', 'AdCert-Test-2026!');
await page.keyboard.press('Enter');
await page.waitForURL((u) => !u.pathname.startsWith('/login'), { timeout: 30000 });
const hdr = async (x = {}) => ({ 'X-CSRF-Token': (await ctx.cookies()).find((c) => c.name === 'ub_csrf')?.value ?? '', ...x });
const get = async (p) => (await (await ctx.request.get(`${api}${p}`)).json()).data;
const post = async (p, data) => (await (await ctx.request.post(`${api}${p}`, { headers: await hdr({ 'Idempotency-Key': randomUUID() }), data })).json()).data;
const rate = async (r) => ctx.request.put(`${api}/metal-rates/today`, { headers: await hdr(), data: { gold_22k: r } });
await rate('11650');
const name = `G3o Kavita ${run}`;
const party = await post('/parties', { name, type: 'customer', is_customer: true });
const nos = (await get('/units')).find((u) => u.code === 'NOS');
const tag = `OB-${run}`;
await post('/items', { name: `G3o bangle ${run}`, unit_id: nos.id, selling_price: '0', tracking: 'serial', tag: { tag_no: tag, purity: 'gold_22k', gross_g: '12.340', stone_g: '0', net_g: '12.340', making_type: 'pct', making_value: '12', wastage_pct: '0' } });
const what = `Bangle ${run}`;
const when = new Date(Date.now() + 5 * 864e5).toISOString().slice(0, 10);
const order = await post('/sales/custom-orders', { client_key: randomUUID(), party_id: party.id, what, purity: 'gold_22k', deliver_on: when, advance: '50000', advance_mode: 'upi', fix_rate: true });
await rate('12000');
await page.goto(`${base}/sales/custom-orders`);
await page.getByPlaceholder('Order, customer or item').fill(what);
await page.waitForTimeout(900);
await page.getByTestId('custom-order-more').first().click();
await page.getByTestId('custom-order-bill').first().click();
await page.waitForURL(/custom_order=/, { timeout: 15000 });
await page.getByTestId('bill-order-note').waitFor({ timeout: 15000 });
const note = await page.getByTestId('bill-order-note').innerText();
check('the bill says which order it delivers, and the fixed rate', note.includes(order.number) && note.includes('₹11,650'), note);
const box = page.getByPlaceholder(/Search or scan item|Search item or scan/).first();
await box.click(); await box.fill(tag); await box.press('Enter');
await page.getByTestId('line-jewel').first().waitFor({ timeout: 10000 });
await page.waitForTimeout(3500);
let draft = null;
for (const r of (await get('/sales/invoices?tab=draft&page_size=8')) ?? []) { const d = await get(`/sales/invoices/${r.id}`); if (d?.lines?.some((l) => l.jewel?.tag_no === tag)) draft = d; }
const want = skew ? '12000.00' : '11650.00';
check(`the line is priced at ${want} though today's rate is 12,000`, draft?.lines?.[0]?.jewel?.rate === want, draft?.lines?.[0]?.jewel?.rate);
check('the draft is linked to the order', draft?.custom_order?.id === order.id);
const n = (s) => Number(String(s).replace(/[^\d.]/g, ''));
const grand = n(await page.getByTestId('invoice-grand-total').first().innerText());
const toPay = n(await page.getByTestId('invoice-to-pay').first().innerText().catch(() => '0'));
check('To pay = total − ₹50,000', Math.abs(grand - 50000 - toPay) < 0.005, `${grand} ${toPay}`);
await page.screenshot({ path: `${dir}/bill-1280.png`, fullPage: true });
const rest = (Number(draft.grand_total) - 50000).toFixed(2);
const issued = await ctx.request.post(`${api}/sales/invoices/${draft.id}/issue`, { headers: await hdr({ 'Idempotency-Key': randomUUID() }), data: { version: draft.version, payment: { mode_breakup: [{ mode: 'cash', amount: rest }] } } });
check('issued with the rest in cash', issued.ok(), String(issued.status()));
const bill = await get(`/sales/invoices/${draft.id}`);
check('the bill is paid in full', bill.status === 'paid' && Number(bill.amount_due) === 0, `${bill.status} due ${bill.amount_due}`);
const after = await get(`/sales/custom-orders/${order.id}`);
check('the order is delivered and names the bill', after.status === 'delivered' && after.invoice_id === draft.id);
const adv = await get(`/payments/${order.advance_payment_id}`);
check('the advance is all used', Number(adv.unallocated_amount) === 0, adv.unallocated_amount);
await rate('11650');
const phone = await browser.newContext({ storageState: await ctx.storageState(), viewport: { width: 320, height: 800 } });
const p = await phone.newPage();
await p.goto(`${base}/sales/custom-orders`);
await p.getByTestId('custom-orders').waitFor({ timeout: 15000 });
await p.waitForTimeout(1000);
const over = await p.evaluate(() => document.documentElement.scrollWidth - innerWidth);
check('320: the list with Make bill fits', over <= 0, `${over}px`);
await p.screenshot({ path: `${dir}/list-320.png` });
await browser.close();
const failed = results.filter((x) => !x).length;
console.log(`\n${results.length - failed}/${results.length} passed, ${errs} console errors${skew ? ' (SKEWED)' : ''}`);
process.exitCode = skew ? (failed ? 0 : 1) : failed || errs ? 1 : 0;
